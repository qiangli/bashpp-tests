// upstreamDirs is the GOROOT/test directory list from the upstream runner's
// `dirs` variable. Anything outside it is not a test case — most importantly a
// "<name>.dir" subdirectory, whose files are inputs to a compiledir/rundir test
// and must never be selected as tests in their own right.
var upstreamDirs = []string{
	".", "ken", "chan", "interface", "internal/runtime/sys", "syntax", "dwarf",
	"fixedbugs", "codegen", "abi", "typeparam", "typeparam/mdempsky", "arenas", "simd",
}

func isUpstreamTestDir(dir string) bool {
	return slices.Contains(upstreamDirs, dir)
}

